// x6XOR decodes one independent X6 block. The next key is selected by the
// encrypted byte, while the current byte is XORed with the previous key.
func x6XOR(data []byte) {
	key := byte(0x7f)
	for i, encrypted := range data {
		data[i] = encrypted ^ key
		key = x6XORPad[encrypted]
	}
}
